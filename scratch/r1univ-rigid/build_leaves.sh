#!/bin/bash
# Compose scratch/r1univ-rigid/R1UnivLeaves.lean: the core R1UnivRigid.lean (verbatim, minus its imports)
# over ZInQKernel.OneProof.H.TailZ12, then parts/{copies,transfer,printed,thms}.lean.
D=scratch/r1univ-rigid
{
  echo "import ZInQKernel.OneProof.H.TailZ12"
  grep '^import' $D/R1UnivRigid.lean | grep -v 'HDecomp.QM.Leaves'
  echo
  echo "/-! Generated by build_leaves.sh: R1UnivRigid.lean (core, verbatim) + parts/*.lean. -/"
  echo
  echo "set_option linter.all false"
  grep -v '^import' $D/R1UnivRigid.lean
  echo
  echo "noncomputable section"
  cat $D/parts/copies.lean $D/parts/transfer.lean $D/parts/printed.lean $D/parts/thms.lean
  echo
  echo "end"
} > $D/R1UnivLeaves.lean
