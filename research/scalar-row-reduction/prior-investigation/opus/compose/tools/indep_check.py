"""Independent checks (compose agent). Reads only raw-translated IRs; imports no stack code.

gates  RAW K      : evaluate every gate of RAW mod a 127-bit prime at random base values (3 trials);
                    assert detector r: q12=q1^23, mixedHigh=q1^46, q_K=q1^(2K-1), E_K.power2/3 = q_K^2, q_K^3.
tri    OLD NEW    : rows matched by name. Forward: old zero -> new zero via T := 42 r W2.
                    Backward: new zero -> old zero via W2 := N^2. Each substituted row must lie in the
                    ideal generated by the other system's rows (checked by explicit cofactors).
rowop  OLD NEW    : same coordinates; every changed row = old row + constant combination of the
                    S.chart.x.{0,1} definition rows (solved by linear algebra over Q, then verified).
"""
import json, sys, random
from fractions import Fraction as Fr
import sympy as sp

P = (1 << 127) - 1


def load(p):
    return json.load(open(p))


def ev_terms(terms, val, S):
    tot = 0
    for t in terms:
        c = Fr(t['coefficient'])
        x = c.numerator * pow(c.denominator, -1, P) % P
        x = x * pow(S, int(t['sPower']), P) % P if int(t['sPower']) >= 0 else x * pow(pow(S, -int(t['sPower']), P), -1, P) % P
        for i in t['monomial']:
            x = x * val[i] % P
        tot += x
    return tot % P


def gates(raw, K):
    d = load(raw)
    E = int(d['fixedParameter']['value'].split('^')[1]); S = pow(3, E, P)
    gated = {g['coordinateId'] for g in d['gates']}
    byname = {c['name']: c['id'] for c in d['coordinates']}
    out = []
    for trial in range(3):
        rnd = random.Random(trial)
        val = {c['id']: rnd.randrange(1, P) for c in d['coordinates'] if c['id'] not in gated}
        for g in d['gates']:
            op = g['operation']
            if op == 'quadratic_assignment':
                v = ev_terms(g['expression'], val, S)
            elif op == 'rational_quotient':
                v = ev_terms(g['numerator'], val, S) * pow(ev_terms(g['denominator'], val, S), -1, P) % P
            elif op == 'field_quotient_component':
                a0, a1 = (ev_terms(x, val, S) for x in g['numerator'])
                b0, b1 = (ev_terms(x, val, S) for x in g['denominator'])
                n = (b0 * b0 - 2 * b1 * b1) % P
                comp = (a0 * b0 - 2 * a1 * b1) if g['component'] == 0 else (a1 * b0 - a0 * b1)
                v = comp * pow(n, -1, P) % P
            else:
                raise ValueError(op)
            val[g['coordinateId']] = v
        for r in range(3):
            q1 = val[byname[f'detector{r}.q1']]
            want = {'q12': 23, 'mixedHigh.quadratic': 46, f'q{K}': 2 * K - 1,
                    f'E{K}.power2.quadratic': 2 * (2 * K - 1), f'E{K}.power3.quadratic': 3 * (2 * K - 1)}
            for n, e in want.items():
                ok = val[byname[f'detector{r}.{n}']] == pow(q1, e, P)
                out.append((trial, r, n, e, ok))
                assert ok, (trial, r, n, e)
    # negative control: wrong exponent must fail
    assert val[byname[f'detector0.q{K}']] != pow(val[byname['detector0.q1']], 2 * K - 3, P)
    print(json.dumps({'status': 'PASS', 'K': K, 'checks': len(out)}))


def polys(d):
    sym = {c['id']: sp.Symbol('c_' + c['name'].replace('.', '_')) for c in d['coordinates']}
    def poly(terms):
        s = sp.Integer(0)
        for t in terms:
            assert int(t['sPower']) == 0 or True
            m = sp.Rational(Fr(t['coefficient']).numerator, Fr(t['coefficient']).denominator) * sp.Symbol('S') ** int(t['sPower'])
            for i in t['monomial']:
                m *= sym[i]
            s += m
        return sp.expand(s)
    return {r['name']: poly(r['terms']) for r in d['residuals']}, {c['name']: sym[c['id']] for c in d['coordinates']}


def tri(old, new):
    """Old: W2 := N^2, T_old := (r - r0)*W2 (pole-internal), Bh_old = e*(W2 + k*T_old).
    New: ri*T = 42 N^2 (r*ri=1 kept), Bh_new = e*T.  Explicit polynomial maps both ways:
      forward  old->new: T := 42 r W2, Bh_new := mu*Bh_old
      backward new->old: W2 := N^2, T_old := its defining rhs, Bh_old := Bh_new/mu
    mu is computed and must be a nonzero constant.  Every row of the target system, after
    substitution, must reduce to 0 modulo the source system's rows (Groebner, QQ)."""
    do, dn = load(old), load(new)
    O, os_ = polys(do); N, ns = polys(dn)
    To, Tn, W2 = os_['scalar.preparationT.quadratic'], ns['scalar.preparationT'], os_['scalar.W2.quadratic']
    Nn, ri, Bh, e = ns['scalar.N'], ns['scalar.rInverse'], ns['scalar.Bh.quadratic'], ns['scalar.normalized_e']
    same = {k for k in set(O) & set(N) if sp.expand(O[k] - N[k]) == 0}
    dO = {k: O[k] for k in O if k not in same}; dN = {k: N[k] for k in N if k not in same}
    print('differing old rows', list(dO), 'differing new rows', list(dN))
    rrow = N['scalar.rInverse.definition']; assert sp.expand(O['scalar.rInverse.definition'] - rrow) == 0
    rr = sp.expand((rrow + 1) / ri); assert sp.expand(rr * ri - 1 - rrow) == 0 and ri not in rr.free_symbols
    Tdef_old = dO['scalar.preparationT.definition']; To_rhs = sp.solve(Tdef_old, To)[0]
    Bh_old_rhs = sp.solve(dO['scalar.Bh.definition'], Bh)[0]
    Bh_old_in_W2 = sp.expand(Bh_old_rhs.subs(To, To_rhs))
    mu = sp.simplify(42 * rr * W2 * e / Bh_old_in_W2)
    print('r =', rr, '; mu =', mu); assert mu.is_number and mu != 0
    Gold = sp.groebner(list(O.values()), *sorted(set().union(*[p.free_symbols for p in O.values()]), key=str), order='grevlex', domain='QQ') if False else None
    # source ideals: only the differing rows plus the r*ri row are needed (others identical after maps)
    fsub = {Tn: 42 * rr * W2, Bh: mu * Bh}
    bsub = {W2: Nn**2, To: To_rhs.subs(W2, Nn**2), Bh: Bh / mu}
    def check(target_rows, sub, src_rows, elim):
        vs = sorted(set().union(*[p.free_symbols for p in list(src_rows) + list(target_rows.values())]), key=str)
        G = sp.groebner(list(src_rows), *elim, *[v for v in vs if v not in elim], order='lex', domain='QQ')
        return {k: G.reduce(sp.expand(sp.sympify(v).xreplace(sub)))[1] == 0 for k, v in target_rows.items()}
    # forward: every new row (identical ones only change if they contain Tn or Bh)
    tgtN = {k: v for k, v in N.items() if k in dN or v.free_symbols & {Tn, Bh}}
    fwd = check(tgtN, fsub, list(dO.values()) + [rrow] + [O[k] for k in O if k in same and O[k].free_symbols & {Bh}], [Bh, To, W2, ri])
    tgtO = {k: v for k, v in O.items() if k in dO or v.free_symbols & {W2, To, Bh}}
    bwd = check(tgtO, bsub, list(dN.values()) + [rrow], [Bh, Tn, ri])
    print('forward', fwd); print('backward', bwd)
    assert all(fwd.values()) and all(bwd.values())
    print(json.dumps({'status': 'PASS', 'identicalRows': len(same), 'mu': str(mu)}))


def rowop(old, new):
    do, dn = load(old), load(new)
    assert [c['name'] for c in do['coordinates']] == [c['name'] for c in dn['coordinates']]
    O, _ = polys(do); N, _ = polys(dn)
    assert set(O) == set(N)
    g0, g1 = O['S.chart.x.0.definition'], O['S.chart.x.1.definition']
    l0, l1 = sp.symbols('l0 l1')
    changed = {}
    for n in O:
        d = sp.expand(N[n] - O[n])
        if d == 0:
            continue
        eqs = sp.Poly(sp.expand(d - l0 * g0 - l1 * g1), *sorted(d.free_symbols | g0.free_symbols | g1.free_symbols, key=str)).coeffs()
        sol = sp.solve(eqs, [l0, l1], dict=True)
        assert sol, n
        assert sp.expand(d - sol[0][l0] * g0 - sol[0][l1] * g1) == 0
        changed[n] = [str(sol[0][l0]), str(sol[0][l1])]
    print(json.dumps({'status': 'PASS', 'changed': changed, 'x0def': str(g0), 'x1def': str(g1)}))


