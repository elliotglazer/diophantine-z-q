def sha(b): return hashlib.sha256(b).hexdigest()
def pin(p):
    b = p.read_bytes()
    return {'path': p.relative_to(ROOT).as_posix(), 'sha256': sha(b), 'bytes': len(b)}
def load(p): return json.loads(p.read_text(encoding='utf-8'))
def write_once(p, value):
    b = (json.dumps(value, indent=2, ensure_ascii=False) + '\n').encode() if not isinstance(value, str) else value.encode()
    if p.exists():
        assert p.read_bytes() == b, f'Refusing to overwrite changed frozen record {p}'
    else:
        p.write_bytes(b)
def check(p):
    actual = pin(ROOT / p['path'])
    assert all(actual[k] == p[k] for k in ('path','sha256','bytes')), p['path']

